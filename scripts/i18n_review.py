#!/usr/bin/env python3
"""Check the Japanese messages and write the human-review list (apps/web/messages/ja.REVIEW.md).

Fails (exit 1) when ja.json is missing a key that en.json has, or a translation for any label that comes
from config/*.yaml (readiness questions, JETRO asks, capabilities, Fit factors, Trust categories...).

Usage: python scripts/i18n_review.py          # check and rewrite ja.REVIEW.md
       python scripts/i18n_review.py --check  # check only; fail if ja.REVIEW.md is out of date
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
MESSAGES = ROOT / "apps" / "web" / "messages"
REVIEW = MESSAGES / "ja.REVIEW.md"


def flatten(d: dict, prefix: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out |= flatten(v, f"{key}.")
        else:
            out[key] = str(v)
    return out


def config_labels() -> dict[str, str]:
    """labels.<key> -> the English source text, for every label the SME pages show from config."""
    trust = yaml.safe_load((ROOT / "config" / "trust_v1.yaml").read_text(encoding="utf-8"))
    fit = yaml.safe_load((ROOT / "config" / "fit_v1.yaml").read_text(encoding="utf-8"))
    gap = yaml.safe_load((ROOT / "config" / "gap_bridge_v1.yaml").read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for d, spec in trust["dimensions"].items():
        out[f"trustDimensions.{d}.label"] = spec["label"]
        out[f"trustDimensions.{d}.question"] = spec["question"]
    out |= {f"trustCategories.{k}": v["label"] for k, v in trust["categories"].items()}
    out |= {f"gates.{k}": v["label"] for k, v in trust["gates"].items()}
    out |= {f"band.{b['label']}": b["label"] for b in trust["bands"]}
    # outlook values are engine output, not config
    out |= {f"outlook.{v}": v for v in ("Positive", "Stable", "Watch", "Not assessed")}
    out |= {f"fitFactors.{k}": v["label"] for k, v in fit["factors"].items()}
    out |= {f"importance.{k}": k for k in fit["importance_multipliers"]}
    out |= {f"fitCategory.{k}": v["label"] for k, v in fit["categories"].items()}
    out |= {f"fitAction.{k}": v["action"] for k, v in fit["categories"].items()}
    out |= {f"sectors.{s}": s for s in fit["vocabularies"]["sectors"]}
    out |= {f"channels.{c}": c for c in fit["vocabularies"]["channels"]}
    out |= {f"afterSales.{n}": n for n in ("none", "basic", "full")}
    out |= {f"severity.{s['label']}": s["label"] for s in gap["severity_labels"]}
    out |= {f"scale.{k}": v for k, v in gap["answer_scale"].items()}
    for d, spec in gap["dimensions"].items():
        out[f"readiness.{d}.label"] = spec["label"]
        out[f"readiness.{d}.ask"] = spec["jetro_ask"]
        out |= {f"questions.{q.replace('.', '_')}": text for q, text in spec["questions"].items()}
    out |= {f"capabilities.{k}": v["label"] for k, v in gap["capabilities"].items()}
    return {f"labels.{k}": v for k, v in out.items()}


def review_text(en: dict[str, str], ja: dict[str, str], sources: dict[str, str]) -> str:
    lines = [
        "# Japanese strings: human review needed before the demo",
        "",
        "<!-- REVIEW: generated by scripts/i18n_review.py from messages/ja.json; do not edit by hand -->",
        "",
        "Every string below was machine-drafted. A fluent Japanese speaker should check each one, edit",
        "`ja.json`, then rerun `python scripts/i18n_review.py`. Numbers, company names and the verdict",
        "words Green / Amber / Red stay as they are; sentences the API writes (verdict reasons, shortlist",
        "reasons) are not translated yet.",
        "",
        "| Key | English source | Japanese (draft) | OK? |",
        "| --- | --- | --- | --- |",
    ]
    cell = lambda s: s.replace("|", "\\|").replace("\n", " ")  # noqa: E731
    for key in sorted(ja):
        source = sources.get(key, en.get(key, ""))
        lines.append(f"| `{key}` | {cell(source)} | {cell(ja[key])} | [ ] |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="fail if ja.REVIEW.md is out of date instead of writing it")
    args = ap.parse_args()
    en = flatten(json.loads((MESSAGES / "en.json").read_text(encoding="utf-8")))
    ja = flatten(json.loads((MESSAGES / "ja.json").read_text(encoding="utf-8")))
    sources = config_labels()

    problems = [f"ja.json is missing {k}" for k in sorted(set(en) - set(ja))]
    problems += [f"ja.json is missing the config label {k}" for k in sorted(set(sources) - set(ja))]
    problems += [f"ja.json has {k}, which neither en.json nor config defines"
                 for k in sorted(set(ja) - set(en) - set(sources))]
    for p in problems:
        print(p, file=sys.stderr)
    if problems:
        return 1

    text = review_text(en, ja, sources)
    if args.check:
        if not REVIEW.exists() or REVIEW.read_text(encoding="utf-8") != text:
            print("ja.REVIEW.md is out of date: run python scripts/i18n_review.py", file=sys.stderr)
            return 1
        return 0
    REVIEW.write_text(text, encoding="utf-8")
    print(f"wrote {REVIEW.relative_to(ROOT)} ({len(ja)} strings)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
